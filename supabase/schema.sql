-- NutriAI schema for the current Flask/psycopg backend.
-- Run once in Supabase Dashboard > SQL Editor > New query > Run.
-- Passwords are Werkzeug password hashes; never insert plaintext passwords.

create table if not exists public.app_users (
    id bigint generated by default as identity primary key,
    email text not null unique,
    password_hash text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.meal_plans (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    plan_name text not null default 'My Weekly Meal Plan',
    plan_data jsonb not null,
    profile_data jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists meal_plans_user_created_idx
    on public.meal_plans(user_email, created_at desc);

create table if not exists public.meal_plan_items (
    id bigint generated by default as identity primary key,
    meal_plan_id bigint not null references public.meal_plans(id) on delete cascade,
    user_email text not null references public.app_users(email) on delete cascade,
    day_number integer,
    meal_category text not null,
    food_name text not null,
    calories numeric,
    protein numeric,
    carbohydrates numeric,
    fat numeric,
    food_data jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists meal_plan_items_user_idx on public.meal_plan_items(user_email);

create table if not exists public.hydration_entries (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    amount_ml integer not null check (amount_ml > 0),
    local_date date not null,
    logged_at timestamptz not null default now(),
    display_time text not null default '',
    created_at timestamptz not null default now()
);
-- The existing Supabase table shown in the dashboard has logged_at. The Flask
-- writer omits it, so ensure PostgreSQL fills it automatically.
alter table public.hydration_entries
    alter column logged_at set default now();
create index if not exists hydration_entries_user_date_idx
    on public.hydration_entries(user_email, local_date);

create table if not exists public.hydration_pet_state (
    id bigint generated by default as identity primary key,
    user_email text not null unique references public.app_users(email) on delete cascade,
    xp integer not null default 0,
    daily_goal_ml integer not null default 2000,
    badges jsonb not null default '[]'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.grocery_items (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    item_name text not null,
    quantity text not null default '1',
    is_purchased boolean not null default false,
    created_at timestamptz not null default now()
);
create index if not exists grocery_items_user_idx on public.grocery_items(user_email, id);

create table if not exists public.saved_recipes (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    recipe_name text not null,
    recipe_data jsonb not null,
    created_at timestamptz not null default now(),
    unique(user_email, recipe_name)
);

-- Supporting tables used by existing dashboard endpoints.
create table if not exists public.pantry_items (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    item_name text not null,
    quantity text not null default '1',
    created_at timestamptz not null default now()
);
create index if not exists pantry_items_user_idx on public.pantry_items(user_email, id);

create table if not exists public.user_preferences (
    id bigint generated by default as identity primary key,
    user_email text not null unique references public.app_users(email) on delete cascade,
    preferences jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.mood_logs (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    mood text not null,
    preferences jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.food_logs (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    food_name text not null,
    quantity text not null default '1',
    nutrition_data jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.nutrition_history (
    id bigint generated by default as identity primary key,
    user_email text not null references public.app_users(email) on delete cascade,
    nutrition_data jsonb not null,
    created_at timestamptz not null default now()
);

-- The Flask server connects directly as the Supabase PostgreSQL database user.
-- Keep these tables out of the browser; do not expose a service-role key there.
