-- Repair NutriAI tables whose id columns are NOT NULL but have no default.
-- Inserts from the Flask app intentionally omit id and expect PostgreSQL to
-- generate it. Existing rows and IDs are preserved.
-- Run this file in Supabase Dashboard > SQL Editor.

do $$
declare
    target_table text;
    sequence_name text;
begin
    foreach target_table in array array[
        'food_logs',
        'grocery_items',
        'hydration_entries',
        'meal_plan_items',
        'meal_plans',
        'nutrition_history',
        'pantry_items',
        'saved_recipes'
    ] loop
        if to_regclass(format('public.%I', target_table)) is null then
            continue;
        end if;

        -- The existing hydration table includes logged_at; the Flask insert
        -- omits it, so give PostgreSQL a timestamp automatically.
        if target_table = 'hydration_entries'
           and exists (
               select 1
               from information_schema.columns as c
               where c.table_schema = 'public'
                 and c.table_name = target_table
                 and c.column_name = 'logged_at'
           ) then
            alter table public.hydration_entries
                alter column logged_at set default now();
        end if;

        if exists (
            select 1
            from information_schema.columns as c
            where c.table_schema = 'public'
              and c.table_name = target_table
              and c.column_name = 'id'
              and c.is_identity = 'NO'
              and c.column_default is null
        ) then
            execute format(
                'alter table public.%I alter column id add generated by default as identity',
                target_table
            );
        end if;

        -- Position the sequence after the largest existing id, if any.
        sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
        if sequence_name is not null then
            execute format(
                'select setval(%L, coalesce((select max(id) from public.%I), 1), exists(select 1 from public.%I))',
                sequence_name,
                target_table,
                target_table
            );
        end if;
    end loop;
end
$$;
